# 2. Тіркелу

| Параметр | Мәні |
|----------|------|
| Файл | `register.php` |
| Қолжетімділік | Қонақ |
| Қай аптада жасалады | 9, 11-апта |

## Мақсаты
Жаңа пайдаланушыны жүйеге тіркеу.

## Беттегі элементтер
- Өрістер: аты (username), email, пароль, парольді қайталау
- «Тіркелу» батырмасы
- «Аккаунт бар ма? Кіру» сілтемесі
- Қателер туралы хабарлама

## Орындалатын функциялар
- Деректерді POST арқылы қабылдау
- Валидация: өрістер бос емес, email форматы, пароль кемінде 8 таңба, парольдер сәйкес
- Username және email бірегейлігін тексеру
- Парольді `password_hash()` арқылы сақтау
- Сәтті тіркелген соң `login.php` бетіне бағыттау

## Қолданылатын кестелер
`users`

## Қауіпсіздік және валидация
- Prepared statements
- CSRF-токен
- Қателерде пароль қайта көрсетілмейді
